def scoresheet(
    material_id: str,
    materials: Registry,
    processes: Registry,
    pillars: Dict[str, Any],
) -> str:
    """One-page per-material scoresheet (all modules exercised)."""
    m = materials.get(material_id)
    lca_row = simulate.lca(m)
    efe = evaluate.efe_score(m, pillars)
    lad = evaluate.ladder_info(m)
    rc = evaluate.risk_class(m)
    mc = simulate.monte_carlo_lca(m, n=500, seed=42)
    cult = m.get("cultivation", {})

    lines = [
        f"=== {m['name']} [`{m['id']}`] ===",
        f"  class/category : {m['class']} / {m['category']}  [{m['status']}]",
        f"  cultivation    : {cult.get('cycle', 'n/a')}",
        f"  yield          : {_fmt_range(cult.get('yield_t_ha_yr'), ' t/ha/yr', 1)}",
        f"  density        : {_fmt_num(m.get('density_g_cm3'), 2, ' g/cm3')}",
        f"  tensile        : {_fmt_range(m.get('tensile_mpa'), ' MPa', 0)}",
        "",
        "  LCA (renewable grid):",
        f"    uptake        : {lca_row['uptake']:.2f} kg CO2/kg",
        f"    processing    : {_fmt_num(lca_row['processing_mj_kg'], 1)} MJ/kg",
        f"    NET CARBON    : {lca_row['net_carbon']:+.2f} kg CO2/kg",
        f"    MC band (p5/p50/p95): {mc['p5']:+.2f} / {mc['p50']:+.2f} / {mc['p95']:+.2f}",
        "",
        "  EFE (seven pillars, [SEED-ESTIMATE]):",
        f"    score/grade   : {efe['score']:.1f} / {efe['grade']}",
        f"    strongest     : {efe['strongest_pillar']}",
        f"    weakest       : {efe['weakest_pillar']}",
        "",
        f"  Ladder         : rung {lad['primary_rung']} ({lad['primary_label']})"
        + (f" + supporting {lad['supporting_labels']}" if lad["supporting_rungs"] else ""),
        f"  EoL stream     : {m.get('eol_stream', 'n/a')}",
        f"  Top risk       : {rc['worst']['risk'] if rc['worst'] else 'none'}"
        f" [{rc['class']}]",
        f"  Applications   : {'; '.join(m.get('applications', [])[:5])}",
        f"  Sources        : {', '.join(m.get('sources', []))}",
    ]
    return "\n".join(lines)
