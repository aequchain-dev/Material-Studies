def _fmt_range(value: Any, unit: str = "", nd: int = 1) -> str:
    rng = as_range(value)
    if rng is None:
        return "n/a"
    if rng[0] == rng[1]:
        return f"{rng[0]:.{nd}f}{unit}"
    return f"{rng[0]:.{nd}f}-{rng[1]:.{nd}f}{unit}"


def _fmt_num(value: Any, nd: int = 2, unit: str = "") -> str:
    if value is None:
        return "n/a"
    return f"{float(value):.{nd}f}{unit}"


def _table(headers: List[str], rows: List[List[str]]) -> List[str]:
    """Markdown table as list of lines."""
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("|" + "|".join(["---"] * len(headers)) + "|")
    for row in rows:
        lines.append("| " + " | ".join(str(c) for c in row) + " |")
    return lines


